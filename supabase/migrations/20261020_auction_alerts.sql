-- Auction alert ingestion + per-recipient delivery tracking.
-- Service-role only: no browser policies are intentionally granted.

create table if not exists auction_alert_listings (
    id bigint generated by default as identity primary key,
    source text not null,
    external_key text not null,
    source_url text not null,
    title text not null,
    address text not null,
    state text not null,
    reserve_price numeric(14, 2) not null,
    auction_date date,
    property_type text,
    first_seen_at timestamptz not null default now(),
    last_seen_at timestamptz not null default now(),
    unique (source, external_key)
);

create index if not exists auction_alert_listings_date_idx
    on auction_alert_listings (auction_date, state, reserve_price);

create table if not exists auction_alert_deliveries (
    id bigint generated by default as identity primary key,
    listing_id bigint not null references auction_alert_listings(id) on delete cascade,
    recipient text not null,
    status text not null check (status in ('sent', 'failed')),
    provider_message_id text,
    error_message text,
    attempted_at timestamptz not null default now(),
    sent_at timestamptz,
    unique (listing_id, recipient)
);

create index if not exists auction_alert_deliveries_status_idx
    on auction_alert_deliveries (status, attempted_at desc);

alter table auction_alert_listings enable row level security;
alter table auction_alert_deliveries enable row level security;
